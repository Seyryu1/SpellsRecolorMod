    internal class WintersGrasp
    {
        private static readonly LogWrapper AssetLogger = LogWrapper.Get("WintersGrasp");
        // Структура для хранения данных об элементальных способностях
        // Меняем FX у projectile, используемого способностью (берём первый из m_Projectiles)
        // Original WintersGrasp FX GUIDs
        public const string SourceFxGuid = "fd21d914e9f6f5e4faa77365549ad0a7";
        public const string WintersGraspAreaEffectGUID = "ba4e3f85c4f540efa537b4745ed467a4";
        public const string WintersGraspAbilityGUID = "406c6e4a631b43ce8f7a77844b75bf75";
        // Массив элементальных способностей с соответствующими FX
        private static readonly ElementalData.ElementalHeritageData[] ElementalHeritages = new[]
        {
            new ElementalData.ElementalHeritageData
